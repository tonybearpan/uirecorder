'use strict';

var path = require('path');

function quote(value) {
    return JSON.stringify(value == null ? '' : value);
}

function selectorFor(value) {
    var selector = String(value == null ? '' : value);
    if (!selector) throw new Error('Playwright migration: command is missing a locator path.');
    if (/^(xpath=|css=|text=|id=|data-testid=)/.test(selector)) return selector;
    if (/^(\/{1,2}html|\/{1,2}\*)/.test(selector)) return 'xpath=' + selector;
    return selector;
}

function generate(rawCommands, options) {
    options = options || {};
    if (!Array.isArray(rawCommands)) throw new TypeError('Raw command file must contain a JSON array.');
    var lines = [
        "'use strict';", '',
        '// Generated by UIRecorder Playwright compatibility engine.',
        '// Review selectors and sensitive test data before committing this file.',
        "var assert = require('assert');",
        "var { chromium } = require('playwright');", '',
        '(async function main() {',
        '    var browser = await chromium.launch({ headless: ' + (options.headless ? 'true' : 'false') + ' });',
        '    var context = await browser.newContext();',
        '    var page = await context.newPage();',
        '    var pages = [page];',
        '    var scope = page;',
        '    var lastLocator = null;',
        '    try {'
    ];
    function add(code) { lines.push('        ' + code); }
    rawCommands.forEach(function (item, index) {
        if (!item || typeof item !== 'object' || typeof item.type !== 'string') {
            throw new TypeError('Invalid raw command at index ' + index + '.');
        }
        var data = item.data, selector;
        switch (item.type) {
        case 'url':
            add('await page.goto(' + quote(data) + ');');
            add('scope = page;');
            break;
        case 'click':
        case 'dblClick':
        case 'mouseMove':
            selector = selectorFor(data && data.path);
            add('lastLocator = scope.locator(' + quote(selector) + ');');
            add('await lastLocator.' + (item.type === 'dblClick' ? 'dblclick' : item.type === 'mouseMove' ? 'hover' : 'click') + '();');
            break;
        case 'sendKeys':
            if (data && data.keys !== undefined) {
                add('if (lastLocator) { await lastLocator.pressSequentially(' + quote(data.keys) + '); } else { await page.keyboard.insertText(' + quote(data.keys) + '); }');
            }
            break;
        case 'select':
            selector = selectorFor(data && data.path);
            add('lastLocator = scope.locator(' + quote(selector) + ');');
            if (data && data.value !== undefined) add('await lastLocator.selectOption({ value: ' + quote(data.value) + ' });');
            else if (data && data.index !== undefined) add('await lastLocator.selectOption({ index: ' + Number(data.index) + ' });');
            else throw new Error('Playwright migration: select command at index ' + index + ' has no value/index; inspect raw JSON.');
            break;
        case 'switchFrame':
            add(data == null || data === '' ? 'scope = page;' : 'scope = page.frameLocator(' + quote(selectorFor(data)) + ');');
            add('lastLocator = null;');
            break;
        case 'switchWindow':
            add('pages = context.pages();');
            add('page = pages[' + Math.max(0, Number(data) || 0) + '] || pages[pages.length - 1];');
            add('if (!page) throw new Error("No browser page available for switchWindow command.");');
            add('scope = page;');
            add('lastLocator = null;');
            break;
        case 'scrollTo':
            add('await page.evaluate(function (pos) { window.scrollTo(pos.x, pos.y); }, ' + JSON.stringify({x:Number(data && data.x)||0,y:Number(data && data.y)||0}) + ');');
            break;
        case 'scrollElementTo':
            selector = selectorFor(data && data.path);
            add('await scope.locator(' + quote(selector) + ').evaluate(function (el, pos) { el.scrollTo(pos.x, pos.y); }, ' + JSON.stringify({x:Number(data && data.x)||0,y:Number(data && data.y)||0}) + ');');
            break;
        case 'waitBody':
            add('await page.waitForLoadState("domcontentloaded");');
            break;
        case 'sleep':
            add('await page.waitForTimeout(' + Math.max(0, Number(data) || 0) + ');');
            break;
        case 'closeWindow':
            add('if (page !== pages[0]) await page.close();');
            add('pages = context.pages();');
            add('page = pages[pages.length - 1] || pages[0];');
            add('scope = page;');
            add('lastLocator = null;');
            break;
        case 'expect':
            if (data && data.type === 'displayed' && data.params && data.params[0]) {
                selector = selectorFor(data.params[0]);
                add('lastLocator = scope.locator(' + quote(selector) + ');');
                add('await lastLocator.waitFor({ state: ' + quote(data.compare === 'equal' && String(data.to) === 'true' ? 'visible' : 'hidden') + ' });');
            } else if (data && data.type === 'text' && data.params && data.params[0]) {
                selector = selectorFor(data.params[0]);
                add('lastLocator = scope.locator(' + quote(selector) + ');');
                add('assert' + (data.compare === 'equal' ? '.strictEqual' : '.notStrictEqual') + '(await lastLocator.textContent(), ' + quote(data.to) + ');');
            } else {
                add('// Unsupported legacy expect variant at raw command index ' + index + '; review this assertion manually.');
            }
            break;
        case 'end':
            break;
        default:
            add('// Legacy command "' + item.type.replace(/[\r\n]/g, '') + '" at index ' + index + ' is not translated automatically.');
            break;
        }
    });
    lines.push('    } finally {', '        await browser.close();', '    }',
        '})().catch(function (error) {', '    console.error(error && error.stack || error);',
        '    process.exitCode = 1;', '});', '');
    return lines.join('\n');
}

function generateFile(rawFile, outputFile, options) {
    var fs = require('fs');
    var inputPath = path.resolve(rawFile);
    var outputPath = path.resolve(outputFile || rawFile.replace(/\.json$/i, '') + '.pw.js');
    var commands;
    try { commands = JSON.parse(fs.readFileSync(inputPath, 'utf8')); }
    catch (error) {
        error.message = 'Unable to read raw command JSON "' + inputPath + '": ' + error.message;
        throw error;
    }
    fs.writeFileSync(outputPath, generate(commands, options), 'utf8');
    return outputPath;
}

module.exports = { generate: generate, generateFile: generateFile, selectorFor: selectorFor };
